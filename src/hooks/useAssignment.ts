// Runs one assignment at a time: wires key input to the typing engine and handles time away.
import { useEffect, useEffectEvent, useReducer, useRef } from "react";
import { generateAssignment, rememberScenario, type Assignment, type AssignmentLength } from "@/game/assignments";
import { assignmentResult, goblinActive } from "@/game/progress";
import { dayNumber } from "@/game/time";
import { applyKey, createTyping, isFinished, shiftTime, type TypingState } from "@/game/typing";
import { useEventStore } from "@/state/eventStore";
import { useGameStore } from "@/state/gameStore";
import { useKeyInput } from "@/state/useKeyInput";
import { useNow } from "./useNow";

type Game = {
  assignment: Assignment;
  typing: TypingState;
  length: AssignmentLength;
  /** Recently used scenarios, so the next assignment is a different one. */
  recentIds: readonly string[];
  /** Typed in goblin mode, so it is about goblins and pays ten times. */
  goblin: boolean;
  /** The document of the day: the first of each day, which pays a bit more. */
  featured: boolean;
};

type Action =
  { type: "key"; key: string; now: number } | { type: "shift"; deltaMs: number } | { type: "next"; game: Game };

// Random text is generated by callers and passed in, so the reducer itself stays pure.
function newGame(
  tier: number,
  length: AssignmentLength,
  recentIds: readonly string[],
  goblin = false,
  featured = false,
): Game {
  const assignment = generateAssignment(tier, length, Math.random, recentIds, goblin);
  return {
    assignment,
    typing: createTyping(assignment.text),
    length,
    recentIds: rememberScenario(recentIds, assignment.scenarioId),
    goblin,
    featured,
  };
}

function reducer(game: Game, action: Action): Game {
  if (action.type === "next") return action.game;
  const typing =
    action.type === "key" ? applyKey(game.typing, action.key, action.now) : shiftTime(game.typing, action.deltaMs);
  return typing === game.typing ? game : { ...game, typing };
}

/**
 * Runs one assignment at a time from the shared key input. Enter starts the next one when finished.
 * Finishing pays the player through the game store. `tier` picks which scenarios are used.
 */
export function useAssignment(tier: number) {
  const input = useKeyInput();
  const finishAssignment = useGameStore((state) => state.finishAssignment);
  const [game, dispatch] = useReducer(reducer, undefined, () => newGame(tier, "short", []));
  const finished = isFinished(game.typing);
  const started = game.typing.startedAt !== null;
  const now = useNow(started && !finished);

  // The last day that had a document of the day, so each day gets one.
  const featuredDay = useRef(-1);

  const start = (length: AssignmentLength) => {
    const state = useGameStore.getState();
    const goblin = goblinActive(state);
    const day = dayNumber(state.stats.secondsPlayed);
    // The first assignment of each day is the document of the day (goblin mode has its own bonus instead).
    // Changing the length of an unfinished document of the day keeps it the document of the day.
    const featured = !goblin && (day !== featuredDay.current || (game.featured && !finished));
    if (featured) featuredDay.current = day;
    dispatch({ type: "next", game: newGame(tier, length, game.recentIds, goblin, featured) });
  };

  // Starting goblin mode swaps the current assignment for a goblin one straight away.
  const onGoblinStart = useEffectEvent(() => start(game.length));
  useEffect(
    () =>
      useGameStore.subscribe((state, previous) => {
        if (state.goblin.active > 0 && previous.goblin.active <= 0) onGoblinStart();
      }),
    [],
  );

  // An effect event always sees the latest game state without re-subscribing to the input on every keystroke.
  const onKey = useEffectEvent((key: string) => {
    // Nothing is typed into the assignment until the player has given their name.
    if (useGameStore.getState().player.name === "") return;
    // Nor while an office event is waiting for an answer.
    if (useEventStore.getState().current !== null) return;
    if (!finished) dispatch({ type: "key", key, now: performance.now() });
    else if (key === "Enter") start(game.length);
  });
  useEffect(() => input.subscribe((key) => onKey(key)), [input]);

  // Pay out once, when the assignment finishes. finishedAt only changes when a new assignment ends.
  const finishedAt = game.typing.finishedAt;
  const report = useEffectEvent(() =>
    finishAssignment(
      assignmentResult(game.typing, performance.now(), game.length, {
        goblin: game.goblin,
        featured: game.featured,
        title: game.assignment.title,
      }),
    ),
  );
  useEffect(() => {
    if (finishedAt !== null) report();
  }, [finishedAt]);

  // Time spent away from the window or tab does not count against the player.
  useEffect(() => {
    let awayAt: number | null = null;
    const away = () => {
      awayAt ??= performance.now();
    };
    const back = () => {
      if (awayAt === null) return;
      dispatch({ type: "shift", deltaMs: performance.now() - awayAt });
      awayAt = null;
    };
    const onVisibility = () => (document.hidden ? away() : back());

    window.addEventListener("blur", away);
    window.addEventListener("focus", back);
    document.addEventListener("visibilitychange", onVisibility);
    return () => {
      window.removeEventListener("blur", away);
      window.removeEventListener("focus", back);
      document.removeEventListener("visibilitychange", onVisibility);
    };
  }, []);

  return {
    assignment: game.assignment,
    typing: game.typing,
    length: game.length,
    goblin: game.goblin,
    featured: game.featured,
    now,
    finished,
    chooseLength: start,
    next: () => start(game.length),
  };
}
